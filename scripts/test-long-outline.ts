async function main() {
  console.log(`输入大纲 ${longOutline.length} 字`);
  const start = Date.now();
  try {
    const result = await parseOutline(longOutline);
    console.log(`=== 解析成功 (${Date.now() - start}ms) ===`);
    console.log('templateKey:', result.templateKey);
    console.log('characters:', result.characters.length, result.characters.map(c => c.name).join(', '));
    console.log('plotNodes:', result.plotNodes.length);
    result.plotNodes.forEach(n => console.log(`  - ${n.index}. ${n.title} (T${n.targetTurn})`));
    console.log('worldState.sceneName:', result.worldState.sceneName);
  } catch (err: any) {
    console.error(`=== 解析失败 (${Date.now() - start}ms) ===`);
    console.error('error:', err.message);
  }
}
main();
